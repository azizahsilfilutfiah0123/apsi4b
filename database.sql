-- 5. CEK HASIL
-- =========================================================

-- Melihat seluruh tabel
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;

-- Melihat data transaksi beserta nama member, membership, dan admin
SELECT
    t.id_transaksi,
    m.nama_member,
    j.nama_jenis,
    t.jumlah_bayar,
    t.status_bayar,
    a.nama_user AS admin
FROM transaksi t
JOIN member m
    ON m.no_member = t.no_member
JOIN jenis_membership j
    ON j.id_jenis = t.id_jenis
JOIN admin a
    ON a.id_admin = t.id_admin
ORDER BY t.id_transaksi;
