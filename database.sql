-- 1. TABEL MASTER

CREATE TABLE member (
    no_member VARCHAR(10) NOT NULL,
    nama_member VARCHAR(100) NOT NULL,
    jenis_kelamin VARCHAR(10) NOT NULL,
    no_hp VARCHAR(15) NOT NULL,
    alamat VARCHAR(255) NOT NULL,
    kota VARCHAR(50) NOT NULL,
    CONSTRAINT pk_member PRIMARY KEY (no_member),
    CONSTRAINT ck_member_jk
        CHECK (jenis_kelamin IN ('Laki-laki', 'Perempuan'))
);

CREATE TABLE jenis_membership (
    id_jenis VARCHAR(5) NOT NULL,
    nama_jenis VARCHAR(30) NOT NULL,
    harga DECIMAL(12,2) NOT NULL,
    durasi_hari SMALLINT NOT NULL,
    CONSTRAINT pk_jenis_membership PRIMARY KEY (id_jenis),
    CONSTRAINT ck_jenis_harga CHECK (harga >= 0),
    CONSTRAINT ck_durasi CHECK (durasi_hari > 0)
);

CREATE TABLE admin (
    id_admin VARCHAR(10) NOT NULL,
    nama_user VARCHAR(100) NOT NULL,
    username VARCHAR(30) NOT NULL,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT pk_admin PRIMARY KEY (id_admin),
    CONSTRAINT uq_admin_username UNIQUE (username)
);

CREATE TABLE cs (
    id_cs VARCHAR(10) NOT NULL,
    nama_cs VARCHAR(100) NOT NULL,
    username VARCHAR(30) NOT NULL,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT pk_cs PRIMARY KEY (id_cs),
    CONSTRAINT uq_cs_username UNIQUE (username)
);


-- 2. TABEL TRANSAKSI DAN TURUNANNYA

CREATE TABLE transaksi (
    id_transaksi VARCHAR(10) NOT NULL,
    tgl_transaksi DATE NOT NULL,
    jenis_transaksi VARCHAR(20) NOT NULL,
    no_member VARCHAR(10) NOT NULL,
    id_jenis VARCHAR(5) NOT NULL,
    metode_bayar VARCHAR(20) NOT NULL,
    status_bayar VARCHAR(20) NOT NULL,
    jumlah_bayar DECIMAL(12,2) NOT NULL,
    tgl_mulai DATE NOT NULL,
    tgl_berakhir DATE NOT NULL,
    id_admin VARCHAR(10) NOT NULL,

    CONSTRAINT pk_transaksi PRIMARY KEY (id_transaksi),

    CONSTRAINT fk_transaksi_member
        FOREIGN KEY (no_member)
        REFERENCES member (no_member)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_transaksi_jenis
        FOREIGN KEY (id_jenis)
        REFERENCES jenis_membership (id_jenis)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_transaksi_admin
        FOREIGN KEY (id_admin)
        REFERENCES admin (id_admin)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT ck_transaksi_bayar
        CHECK (jumlah_bayar >= 0),

    CONSTRAINT ck_transaksi_tgl
        CHECK (tgl_berakhir >= tgl_mulai)
);

CREATE TABLE check_in (
    id_checkin VARCHAR(10) NOT NULL,
    no_member VARCHAR(10) NOT NULL,
    tgl_checkin DATE NOT NULL,
    jam_checkin TIME NOT NULL,

    CONSTRAINT pk_check_in PRIMARY KEY (id_checkin),

    CONSTRAINT fk_checkin_member
        FOREIGN KEY (no_member)
        REFERENCES member (no_member)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE kartu_member (
    id_kartu VARCHAR(10) NOT NULL,
    status_kartu VARCHAR(20) NOT NULL,
    no_member VARCHAR(10) NOT NULL,
    id_admin VARCHAR(10) NOT NULL,

    CONSTRAINT pk_kartu_member PRIMARY KEY (id_kartu),

    CONSTRAINT fk_kartu_member
        FOREIGN KEY (no_member)
        REFERENCES member (no_member)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_kartu_admin
        FOREIGN KEY (id_admin)
        REFERENCES admin (id_admin)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE notifikasi (
    id_notifikasi VARCHAR(10) NOT NULL,
    jenis_notifikasi VARCHAR(30) NOT NULL,
    no_member VARCHAR(10) NOT NULL,
    id_transaksi VARCHAR(10) NOT NULL,

    CONSTRAINT pk_notifikasi PRIMARY KEY (id_notifikasi),

    CONSTRAINT fk_notifikasi_member
        FOREIGN KEY (no_member)
        REFERENCES member (no_member)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_notifikasi_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES transaksi (id_transaksi)
        ON UPDATE CASCADE ON DELETE RESTRICT
);


-- 3. TABEL JADWAL, LAPORAN, DAN OWNER

CREATE TABLE jadwal_piket (
    id_jadwal VARCHAR(10) NOT NULL,
    tgl_piket DATE NOT NULL,
    jam_mulai TIME NOT NULL,
    id_admin VARCHAR(10) NOT NULL,
    id_cs VARCHAR(10) NOT NULL,

    CONSTRAINT pk_jadwal_piket PRIMARY KEY (id_jadwal),

    CONSTRAINT fk_jadwal_admin
        FOREIGN KEY (id_admin)
        REFERENCES admin (id_admin)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_jadwal_cs
        FOREIGN KEY (id_cs)
        REFERENCES cs (id_cs)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE laporan_fasilitas (
    id_laporan INT GENERATED BY DEFAULT AS IDENTITY,
    nama_fasilitas VARCHAR(50) NOT NULL,
    status_laporan VARCHAR(20) NOT NULL,
    id_cs VARCHAR(10) NOT NULL,

    CONSTRAINT pk_laporan_fasilitas PRIMARY KEY (id_laporan),

    CONSTRAINT fk_laporan_cs
        FOREIGN KEY (id_cs)
        REFERENCES cs (id_cs)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE owner (
    id_owner VARCHAR(10) NOT NULL,
    keadaan_fasilitas_gym VARCHAR(255) NOT NULL,
    pembukuan_gym VARCHAR(255) NOT NULL,
    id_laporan INT NOT NULL,

    CONSTRAINT pk_owner PRIMARY KEY (id_owner),

    CONSTRAINT fk_owner_laporan
        FOREIGN KEY (id_laporan)
        REFERENCES laporan_fasilitas (id_laporan)
        ON UPDATE CASCADE ON DELETE RESTRICT
);


